-- ── 4. 商品: 60 件（跨商户/类目，含下架与 0 库存边界值） ───────────
INSERT INTO products (merchant_id, category_id, sku, name, condition,
                      price, stock, weight_g, dimensions, specs, keywords, is_active)
SELECT
    m.id,
    c.id,
    'SKU-' || LPAD(s.g, 4, '0'),
    CASE MOD(s.g, 6)
        WHEN 0 THEN '银河' WHEN 1 THEN '星尘' WHEN 2 THEN '云雾'
        WHEN 3 THEN '青柠' WHEN 4 THEN '暖阳' ELSE '拾光' END
    || CASE MOD(s.g, 6)
        WHEN 0 THEN '笔记本' WHEN 1 THEN '机械键盘' WHEN 2 THEN '雪梨汁'
        WHEN 3 THEN '精华露' WHEN 4 THEN '冲锋屋' ELSE '悬疑小说集' END
    || ' ' || LPAD(s.g, 2, '0'),
    CASE MOD(s.g, 5)
        WHEN 0 THEN 'new' WHEN 1 THEN 'new' WHEN 2 THEN 'new'
        WHEN 3 THEN 'refurbished' ELSE 'used' END,
    CASE WHEN MOD(s.g, 20) = 0 THEN 99.90
         ELSE 100 + MOD(TRUNC(s.g * 13.37), 4800) END,
    CASE WHEN MOD(s.g, 23) = 0 THEN 0 ELSE 20 + MOD(s.g, 480) END,
    120 + s.g * 7.5,
