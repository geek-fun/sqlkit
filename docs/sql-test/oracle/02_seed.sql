-- ── 7. 明细: 每单 1-4 行（数量 1-3、按 MOD 打散取一件商品） ────────
INSERT INTO order_items (order_id, order_date, product_id, quantity, unit_price)
SELECT o.id, o.order_date, pp.id, 1 + MOD(i.lv, 3), pp.price
FROM orders o
CROSS APPLY (SELECT LEVEL AS lv FROM dual
             CONNECT BY LEVEL <= 1 + MOD(o.id, 4)) i
CROSS APPLY (SELECT p.id, p.price
             FROM products p
             WHERE p.is_active
             ORDER BY MOD(p.id * 31 + o.id, 97), p.id
             FETCH FIRST 1 ROW ONLY) pp;

-- ── 8. 合计回填到订单主表（关联子查询 UPDATE） ────────────────────
UPDATE orders o
   SET o.total_amount = (SELECT NVL(SUM(oi.quantity * oi.unit_price), 0)
                         FROM order_items oi
                         WHERE oi.order_id = o.id AND oi.order_date = o.order_date);

-- ── 9. 支付: 已取消订单不产生支付；复合 FK + ON DELETE SET NULL ────
INSERT INTO payments (order_id, order_date, external_no, amount,
                      payment_channel, status, paid_at, payload)
SELECT o.id,
       o.order_date,
       'PAY' || o.order_no,
       o.total_amount,
       CASE MOD(o.id, 3) WHEN 0 THEN 'alipay' WHEN 1 THEN 'wechat' ELSE 'unionpay' END,
       o.status,
       o.placed_at + NUMTODSINTERVAL(3, 'MINUTE'),
       HEXTORAW(STANDARD_HASH('payload' || o.order_no, 'SHA256'))
FROM orders o
WHERE o.status <> 'cancelled';

-- ── 10. 评价: 已完成订单用户对最贵一件商品打分（ROW_NUMBER 防重复评价） ──
INSERT INTO reviews (payment_id, user_id, product_id, rating, content)
SELECT v.payment_id, v.user_id, v.product_id, v.rating, v.content
FROM (
    SELECT pm.id AS payment_id,
           o.user_id,
           top.product_id,
           1 + MOD(o.id + top.oi_id, 5) AS rating,
           CASE MOD(o.id, 5)
               WHEN 0 THEN '很好用，物流很快' WHEN 1 THEN '一般般吧'
               WHEN 2 THEN '回购无数次' WHEN 3 THEN '包装精美'
               ELSE '凑单买的，还行' END AS content,
           ROW_NUMBER() OVER (PARTITION BY o.user_id, top.product_id
                              ORDER BY o.id) AS rn
    FROM orders o
    CROSS APPLY (SELECT oi.id AS oi_id, oi.product_id
                 FROM order_items oi
                 WHERE oi.order_id = o.id AND oi.order_date = o.order_date
                 ORDER BY oi.unit_price DESC, oi.id
                 FETCH FIRST 1 ROW ONLY) top
    JOIN payments pm ON pm.order_id = o.id
    WHERE o.status = 'completed'
) v
WHERE v.rn = 1;

