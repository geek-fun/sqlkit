INSERT INTO coupons (code, discount, min_amount, valid_until, claimed_by, claimed_at)
SELECT TO_CHAR(coupon_code_seq.NEXTVAL),
       5 + s.g * 2.5,
       100 + s.g * 10,
       TIMESTAMP '2026-12-31 00:00:00 +08:00',
       CASE WHEN MOD(s.g, 4) = 0
            THEN (SELECT u.id FROM users u
                  WHERE u.username = 'user_' || (1 + MOD(s.g * 3, 400)))
            ELSE NULL END,
       CASE WHEN MOD(s.g, 4) = 0
            THEN SYSTIMESTAMP - NUMTODSINTERVAL(s.g, 'DAY') ELSE NULL END
FROM (SELECT LEVEL AS g FROM dual CONNECT BY LEVEL <= 24) s;

