JOIN (SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS rn FROM merchants) m
  ON m.rn = 1 + MOD(s.g, 10)
JOIN categories c
  ON c.id = CASE WHEN MOD(s.g, 5) = 1 THEN 7
                 WHEN MOD(s.g, 5) = 2 THEN 1
                 WHEN MOD(s.g, 5) = 3 THEN 2
                 ELSE 3 + MOD(s.g, 4) END;

