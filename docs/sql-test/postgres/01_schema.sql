-- ── 15. 函数/过程（含同名跨 schema 重载 → procedures/functions 面板）
CREATE FUNCTION store.get_product_rank(pid int)
RETURNS TABLE (product_id bigint, sold_qty bigint, revenue numeric)
LANGUAGE sql STABLE AS $$
    SELECT oi.product_id, sum(oi.quantity)::bigint, sum(oi.line_total)
    FROM store.order_items oi
    WHERE oi.product_id = pid
    GROUP BY oi.product_id
$$;

CREATE FUNCTION store.get_product_rank(pid bigint) -- 同 schema 重载
RETURNS TABLE (product_id bigint, sold_qty bigint, revenue numeric)
LANGUAGE plpgsql STABLE AS $$
BEGIN
    RETURN QUERY
    SELECT oi.product_id, sum(oi.quantity)::bigint, sum(oi.line_total)
    FROM store.order_items oi
    WHERE oi.product_id = pid
    GROUP BY oi.product_id;
END;
$$;

CREATE FUNCTION analytics.get_product_rank(n integer) -- 跨 schema 同名
RETURNS TABLE (product_id bigint, sold_qty bigint, revenue numeric)
LANGUAGE sql STABLE AS $$
    SELECT t.product_id, t.qty, t.rev
    FROM (SELECT oi.product_id   AS product_id,
                 sum(oi.quantity) AS qty,
                 sum(oi.line_total) AS rev
          FROM store.order_items oi GROUP BY oi.product_id) t
    LIMIT n
$$;

CREATE PROCEDURE store.claim_coupon(coupon_code text, for_user bigint) -- CALL-able
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE store.coupons
       SET claimed_by = for_user, claimed_at = now()
     WHERE code = coupon_code
       AND claimed_by IS NULL
       AND valid_until > now();
END;
$$;

CREATE PROCEDURE store.void_order(target_order_no text) -- 多过程
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE store.orders
       SET status = 'cancelled'
     WHERE order_no = target_order_no
       AND status IN ('draft', 'paid');
END;
$$;

-- ── 16. 触发器（行级 BEFORE/AFTER + 语句级，覆盖 INSERT/UPDATE/DELETE）
CREATE OR REPLACE FUNCTION store.audit_shield()
RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    row_pk   bigint;
    snapshot jsonb;
BEGIN
    IF TG_LEVEL = 'ROW' THEN
        row_pk := CASE WHEN TG_OP = 'DELETE'
                       THEN (to_jsonb(OLD) ->> 'id')::bigint
                       ELSE (to_jsonb(NEW) ->> 'id')::bigint
                  END;
        snapshot := CASE WHEN TG_OP = 'DELETE'
                         THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
    ELSE
        row_pk := NULL;
        snapshot := jsonb_build_object('statement_op', TG_OP);
    END IF;
    INSERT INTO store.audit_log (table_name, op_type, row_pk, snapshot)
    VALUES (TG_TABLE_NAME, TG_OP, row_pk, snapshot);
    RETURN CASE WHEN TG_LEVEL = 'ROW'
                THEN (CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END)
                ELSE NULL END;   -- 语句级触发器不返回行
END;
$$;

CREATE TRIGGER trg_orders_audit          -- 行级 多事件
AFTER INSERT OR UPDATE OR DELETE ON store.orders
FOR EACH ROW EXECUTE FUNCTION store.audit_shield();

CREATE TRIGGER trg_products_before_set   -- 行级 BEFORE
BEFORE UPDATE ON store.products
FOR EACH ROW EXECUTE FUNCTION store.audit_shield();

CREATE TRIGGER trg_reviews_statement     -- 语句级
AFTER INSERT ON store.reviews
FOR EACH STATEMENT EXECUTE FUNCTION store.audit_shield();

-- ── 17. 视图（可更新视图 / WITH CHECK OPTION / security_barrier） ──
CREATE VIEW store.active_products AS
SELECT id, merchant_id, category_id, sku, name, price, stock, keywords
FROM store.products WHERE is_active AND stock > 0;

CREATE VIEW store.product_catalog WITH (security_barrier = true) AS
SELECT p.id, p.name, p.price, m.name AS merchant_name
FROM store.products p JOIN store.merchants m ON m.id = p.merchant_id;

CREATE VIEW store.shop_with_check AS
SELECT * FROM store.active_products WHERE price < 10000
WITH CHECK OPTION; -- PG 语法:选项在语句末尾

-- ── 18. 物化视图（+ 唯一索引 + 视图嵌套） ──────────────────────────
CREATE MATERIALIZED VIEW analytics.daily_sales AS
SELECT o.order_date                        AS sales_day,
       count(DISTINCT o.id)                AS order_cnt,
       sum(oi.quantity)                    AS units_sold,
       sum(oi.line_total)                  AS revenue
FROM store.orders o
JOIN store.order_items oi
  ON oi.order_id = o.id AND oi.order_date = o.order_date
GROUP BY o.order_date;

CREATE UNIQUE INDEX uq_daily_sales_day ON analytics.daily_sales (sales_day);
CREATE INDEX idx_daily_sales_revenue ON analytics.daily_sales (revenue DESC);

CREATE VIEW analytics.sales_dashboard AS
SELECT sales_day, order_cnt, revenue FROM analytics.daily_sales
UNION ALL
SELECT current_date, 0, 0::numeric;

