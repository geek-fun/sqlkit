CREATE TABLE store.coupons (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE DEFAULT nextval('store.coupon_code_seq')::text,
    discount    numeric(12,2) NOT NULL CHECK (discount > 0),
    min_amount  numeric(12,2) NOT NULL DEFAULT 0,
    valid_until timestamptz NOT NULL,
    claimed_by  bigint REFERENCES store.users (id) ON DELETE CASCADE,
    claimed_at  timestamptz,
    CONSTRAINT coupons_claim_once
        EXCLUDE USING btree (id WITH =) WHERE (claimed_by IS NOT NULL)
);

