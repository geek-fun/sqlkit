-- ── 10. store.order_items（复合外键 + 生成列） ─────────────────────
CREATE TABLE store.order_items (
    id         bigint GENERATED ALWAYS AS IDENTITY,
    order_id   bigint NOT NULL,
    order_date date NOT NULL,
    product_id bigint NOT NULL,
    quantity   int NOT NULL CHECK (quantity > 0),
    unit_price numeric(12,2) NOT NULL CHECK (unit_price > 0),
    line_total numeric(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED, -- 生成列
    PRIMARY KEY (id, order_date),
    CONSTRAINT fk_items_order FOREIGN KEY (order_id, order_date) -- 复合外键
        REFERENCES store.orders (id, order_date) ON DELETE CASCADE,
    CONSTRAINT fk_items_product FOREIGN KEY (product_id)
        REFERENCES store.products (id) ON DELETE RESTRICT
);
CREATE INDEX idx_order_items_product ON store.order_items (product_id);

-- ── 11. store.payments（ON DELETE SET NULL / 未命名 FK 组合） ──────
