-- ── 8. store.products（复合主键 + 双外键 + GIN trigram） ───────────
CREATE TABLE store.products (
    id          bigint GENERATED ALWAYS AS IDENTITY,
    merchant_id bigint NOT NULL,
    category_id int REFERENCES store.categories(id) ON DELETE SET NULL,
    sku         text NOT NULL,
    name        text NOT NULL,
    condition   public.product_condition NOT NULL DEFAULT 'new',
    price       public.cny_price NOT NULL CHECK (price > 0),
    stock       int NOT NULL DEFAULT 0 CHECK (stock >= 0),
    weight_g    numeric(8,1),
    dimensions  public.money_amount,
    specs       jsonb NOT NULL DEFAULT '{}',
    keywords    text[] NOT NULL DEFAULT '{}',
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id, merchant_id),            -- 复合主键
    UNIQUE (id),                              -- 供单列 FK 引用
    CONSTRAINT fk_products_merchant FOREIGN KEY (merchant_id)
        REFERENCES store.merchants(id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_products_category ON store.products (category_id);
CREATE INDEX idx_products_name_trgm ON store.products USING gin (name gin_trgm_ops);
CREATE INDEX idx_products_price_partial ON store.products (price)
    WHERE is_active AND price > 100;          -- 部分索引
CREATE UNIQUE INDEX uq_products_sku ON store.products (lower(sku), merchant_id);

-- ── 9. store.orders（RANGE 分区 + 复合主键 + 复合外键源头） ────────
