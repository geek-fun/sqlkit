-- ── 5. store.users（长列 + 全类型覆盖 + deferrable 唯一约束） ───────
CREATE TABLE store.users (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username      text NOT NULL CHECK (char_length(username) BETWEEN 2 AND 64),
    email         text NOT NULL CHECK (email ~ '^[^@]+@[^@]+\.[^@]+$'),
    phone         text,
    password_hash text NOT NULL,
    locale        char(5) NOT NULL DEFAULT 'zh_CN',
    balance       public.cny_price NOT NULL DEFAULT 0,
    registered_at timestamptz NOT NULL DEFAULT now(),
    last_login_at timestamptz,
    attrs         jsonb NOT NULL DEFAULT '{}',
    tags          text[] NOT NULL DEFAULT '{}',
    signup_ip     inet,
    geo           point,
    avatar        bytea,
    bio           xml,
    wallet        public.money_amount,
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_unique UNIQUE (email)
        DEFERRABLE INITIALLY DEFERRED
);
-- 表达式排他约束 = 可延迟的大小写不敏感邮箱唯一索引（见 03 的邮箱交换演示）
ALTER TABLE store.users ADD CONSTRAINT uq_users_lower_email
    EXCLUDE USING btree ((lower(email)) WITH =) DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX gin_users_attrs ON store.users USING gin (attrs jsonb_path_ops);
CREATE INDEX idx_users_tags ON store.users USING gin (tags);
CREATE INDEX idx_users_registered_brin ON store.users USING brin (registered_at)
    WITH (pages_per_range = 16);

COMMENT ON TABLE  store.users IS '平台注册用户（含 PII 测试字段）';
COMMENT ON COLUMN store.users.balance IS '钱包余额（人民币）';
COMMENT ON COLUMN store.users.email  IS '登录邮箱';

-- ── 6. store.merchants ────────────────────────────────────────────
